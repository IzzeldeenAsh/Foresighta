const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const entries = [];
function walk(directory) {
  for (const item of fs.readdirSync(directory, { withFileTypes: true })) {
    const absolute = path.join(directory, item.name);
    if (item.isDirectory()) { walk(absolute); continue; }
    if (!item.name.endsWith('.ts') || item.name.endsWith('.spec.ts')) continue;
    const source = ts.createSourceFile(absolute, fs.readFileSync(absolute, 'utf8'), ts.ScriptTarget.Latest, true);
    for (const node of source.statements) {
      if (!ts.isClassDeclaration(node) || !node.name) continue;
      const decorator = (ts.getDecorators(node) || []).find(d => ts.isCallExpression(d.expression) && d.expression.expression.getText(source) === 'Component');
      if (!decorator) continue;
      const metadata = decorator.expression.arguments[0];
      if (!metadata || !ts.isObjectLiteralExpression(metadata)) continue;
      const entry = { name: node.name.text, selector: '', files: [path.relative(root, absolute).split(path.sep).join('/')] };
      for (const property of metadata.properties) {
        if (!ts.isPropertyAssignment(property)) continue;
        const name = property.name.getText(source);
        if (name === 'selector' && ts.isStringLiteralLike(property.initializer)) entry.selector = property.initializer.text;
        if (['templateUrl', 'styleUrl', 'styleUrls'].includes(name)) {
          const values = ts.isArrayLiteralExpression(property.initializer) ? property.initializer.elements : [property.initializer];
          for (const value of values) if (ts.isStringLiteralLike(value)) {
            const file = path.resolve(directory, value.text);
            if (fs.existsSync(file)) entry.files.push(path.relative(root, file).split(path.sep).join('/'));
          }
        }
      }
      entries.push(entry);
    }
  }
}
walk(path.join(root, 'src/app'));
const output = '// Generated by npm run dev:sources. Restart npm start after adding or renaming components.\nexport const componentSources: { name: string; selector: string; files: string[] }[] = ' + JSON.stringify(entries, null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'src/app/dev/component-sources.ts'), output);
console.log(`Indexed ${entries.length} developer component sources.`);
